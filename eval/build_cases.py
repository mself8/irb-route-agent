def locate(phrase: str, text: str) -> tuple[int, int]:
    i = text.find(phrase)
    if i < 0:
        raise ValueError(f"근거 구간이 masked_text에 없음: {phrase}")
    return i, i + len(phrase)


def build(case: dict) -> dict:
    masked, log = pii.mask(case["plan_text"])
    facts = []
    for key, label in FACT_LABELS.items():
        fact = {"key": key, "label": label, "value": None, "span": None, "span_start": None, "span_end": None,
                "status": "not_found", "cross_check": None}
        if key in case["facts"]:
            value, phrase = case["facts"][key]
            s, e = locate(phrase, masked)
            fact.update(value=value, span=phrase, span_start=s, span_end=e, status="found", cross_check="agree")
        facts.append(fact)
    expected = dict(case["expected"], unscored_facts=case["unscored"])
    return {"id": case["id"], "title": case["title"], "_note": f"{DRAFT} · 가상 계획서 · 출처: {case['source']} · {case['note']}",
            "institution_name": case["institution_name"], "plan_text": case["plan_text"],
            "pending": {"masked_text": masked, "mask_log": log, "facts": facts}, "expected": expected}


