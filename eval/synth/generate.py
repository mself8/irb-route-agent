def start_dates(rng, n):
    """목표 개시일: 2026-11-01 ~ 2027-06-30 사이에 고르게."""
    first, span = date(2026, 11, 1), (date(2027, 6, 30) - date(2026, 11, 1)).days
    days = [round(i * span / (n - 1)) for i in range(n)]
    rng.shuffle(days)
    return [first + timedelta(days=d) for d in days]


def build():
    rng = random.Random(SEED)
    cris_src = load_cris()
    starts = start_dates(rng, N_TOTAL)
    # CRIS 80건
    cris_cases = []
    for seq, spec in CRIS_SPEC.items():
        for v in spec["variants"]:
            cris_cases.append(cris_case(seq, cris_src[seq], v, rng, starts[len(cris_cases)]))
    # 시나리오 220건: 기관은 제약이 큰 슬롯부터, 지금까지 적게 쓴 기관을 고른다
    slots = make_slots(rng)
    for s in slots:
        fix_state(s)
    count = Counter(c["institution"] for c in cris_cases)
    elig = []
    for i, s in enumerate(slots):
        ok = [inst for inst in INSTITUTIONS if any(placements(tp, s, inst) for tp in TOPICS)]
        elig.append((len(ok), i, ok))
    elig.sort()
    inst_of = {}
    for _, i, ok in elig:
        best = min(ok, key=lambda x: (count[x], rng.random()))
        inst_of[i] = best
        count[best] += 1
    # 가상생활연구소 협약 상황을 돌려 가며 배정 (CRIS 쪽 개수까지 맞춘다)
    c_count = Counter(c["strata"]["IRB 협약"] for c in cris_cases if c["institution"] == "가상생활연구소")
    topic_use = Counter()
    scen = []
    for i, s in enumerate(slots):
        inst = inst_of[i]
        if inst == "가상생활연구소":
            s["contract"] = min(["공용위원회", "타 기관", "언급 없음", "없음"], key=lambda x: (c_count[x], x))
            c_count[s["contract"]] += 1
            s["contract_partner"] = rng.choice(["가상대학교병원", "가상대학교"])
        cands = [tp for tp in TOPICS if placements(tp, s, inst)]
        tp = min(cands, key=lambda t: (topic_use[t["t"]], rng.random()))
        topic_use[tp["t"]] += 1
        opts = placements(tp, s, inst)
        place = opts[-1] if len(opts) > 1 and rng.random() < 0.55 else opts[0]   # 둘 다 되면 '다름'을 조금 더
        scen.append(scenario_case(s, inst, tp, place, rng, starts[80 + i]))
    # 섞어서 번호를 붙인다
    allc = cris_cases + scen
    rng.shuffle(allc)
    cases = []
    for k, c in enumerate(allc, 1):
        route, committee, trace = gold_route(c)
        case = {"id": f"SYN-{k:03d}", "strata": c["strata"], "institution": c["institution"],
                "target_start_date": c["start"], "plan": c["plan"], "facts_gold": c["facts_gold"],
                "route_expected": route, "committee_expected": committee, "decision_trace": trace,
                "pii_gold": c["pii_gold"]}
        if "cris" in c:
            case["cris"] = c["cris"]
        cases.append(case)
    return {"seed": SEED, "note": NOTE, "cases": cases}


