def placements(tp, slot, inst):
    """주제·슬롯·기관이 맞으면 가능한 (소속·보유 관계, 보유 기관) 목록. 안 맞으면 []."""
    kind = ALL_INST[inst][0]
    st, f01, site = slot["state"], slot["f01"], tp["site"]
    if tp["f01"] != f01 or tp.get("kind", "일반") != slot["sub"] or st not in tp["states"]:
        return []
    if tp.get("own") and kind != tp["own"]:
        return []
    if slot["sub"] in ("의약품", "의료기기") or tp.get("trial"):
        return [("같음", inst)] if kind == "병원" else []
    if site in ("무관", "학교"):
        return [("같음" if tp.get("own") else "해당 없음", inst if tp.get("own") else None)]
    if site == "병원":
        opts = [("같음", inst)] if kind == "병원" else []
        if f01 == "기록 이용" and st in ("가명", "익명"):
            opts.append(("다름", "*병원"))
        elif f01 == "인체유래물" and st in ("코드화", "익명") and kind in ("대학", "공공"):
            opts.append(("다름", "*병원"))
        elif f01 in ("중재", "관찰", "설문·면담") and kind in ("대학", "공공", "병원") and not tp.get("own"):
            opts.append(("다름", "*병원"))
        return opts
    if site == "공공":
        if inst == "질병관리청":
            return [("같음", inst)]
        return [("다름", "질병관리청")] if st in ("가명", "익명") else []
    if site == "공단":
        return [("다름", "*공단")] if st in ("가명", "익명") else []
    if site == "대학":
        return [("같음", inst)] if kind == "대학" else []
    if site == "연구소":
        return [("같음", inst)] if inst == "가상생활연구소" else []
    if site == "은행":
        return [("같음", inst)] if inst == "질병관리청" else [("다름", "국립인체자원은행")]
    return []


