S_RULE = {"중재": "S1", "관찰": "S2", "설문·면담": "S2", "기록 이용": "S3", "인체유래물": "S6"}


def gold_route(case):
    """정답 (경로, 위원회, 규칙 ID 목록)을 돌려준다.

    순서: G 범위 → T 임상시험 → S 연구 유형 → J 관할 → E 면제 후보 → C 동의 → P 제공 → D 가명정보.
    판정에는 facts_gold와 기관 속성, strata에 적은 시나리오 설정만 쓴다.
    """
    f, st = case["facts_gold"], case["strata"]
    # 1. G 범위 필터: 배아·유전자 연구면 여기서 끝낸다 (G1).
    if f["F14"] == "예":
        return "범위 밖", "out", ["G1"]
    # 2. T 특별법: 약사법·의료기기법 임상시험이면 그 경로로 끝낸다 (G4 → T1/T4).
    if f["F10"] == "예":
        return "임상시험", "trial", ["G4", "T1" if st["임상시험"] == "의약품" else "T4"]
    # 3. S 연구 유형.
    trace = [S_RULE[f["F01"]]]
    if f["F09"] == "예" and f["F01"] != "인체유래물":
        trace.append("S6")
    # 4. J 관할 위원회. 면제 확인도 관할 위원회가 하므로 면제보다 먼저 본다.
    irb = ALL_INST[case["institution"]][1]
    if irb is None:                          # 소속 없음 → 공용위원회 (J8)
        committee = "public"
        trace.append("J8")
    elif irb:                                # 자체 IRB (J1·J2)
        committee = "own"
        trace += ["J1", "J2"]
    elif st["IRB 협약"] == "공용위원회":       # 공용위원회와 위탁 협약 (J3·J7)
        committee = "public"
        trace += ["J1", "J3", "J7"]
    elif st["IRB 협약"] == "타 기관":          # 인증 기관위원회와 위탁 협약 (J3·J7)
        committee = "contract"
        trace += ["J1", "J3", "J7"]
    else:                                    # IRB도 협약도 없거나 모름 → 기관확인
        committee = "unknown"
        trace += ["J1", "J2", "J3"]
    if len(f["F12"] or []) >= 2:             # 둘 이상 기관 (J10, 기본은 각 소속 IRB)
        trace.append("J10")
    # 5. E 심의면제 후보. 결과는 늘 '후보'다.
    e_rule = None
    if f["F16"] == []:                       # 개인식별정보를 수집·기록하지 않음
        if f["F01"] == "기록 이용":
            e_rule = "E3"
        elif f["F01"] == "인체유래물":
            e_rule = "E5"
        elif f["F01"] == "중재" and f["F09"] != "예":
            e_rule = "E1"
        elif f["F01"] in ("관찰", "설문·면담") and f["F09"] != "예" and not f["F07"]:
            e_rule = "E2"
    if e_rule:
        trace.append(e_rule)
        if e_rule in ("E1", "E2") and f["F08"]:
            trace.append("E4")               # 취약 대상 → 면제 불가
    # 6. C 동의.
    bio = f["F01"] == "인체유래물"
    if f["F11"] == "서면동의":
        trace.append("C4" if bio else "C1")
    elif f["F11"] == "동의면제 요청":
        trace.append("C5" if bio else "C3")
    if "미성년자" in (f["F08"] or []):
        trace.append("C2")
    # 7. P 제3자 제공.
    if f["F06"] == "예" and st["결합·반출"] == "반출":
        if bio:
            trace.append("P2")
        elif st["데이터 상태"] in ("식별", "코드화"):
            trace.append("P1")
    # 8. D 보건의료데이터. 가명정보를 동의 없이 쓰면 DRB 경로(D1·D6).
    pseudo_no_consent = f["F03"] == "가명처리" and f["F11"] != "서면동의"
    if f["F03"] == "가명처리":
        if pseudo_no_consent:
            trace.append("D1")
            if f["F06"] == "예" and st["결합·반출"] == "결합":
                trace.append("D3")
            if f["F07"]:
                trace.append("D4")
            trace += ["D6", "D7"]
        else:
            trace.append("D2")               # 동의 받은 가명정보 → DRB 트리거 아님
    # 경로 요약. 관할을 못 정하면 미정. 그다음 가명·무동의면 A.
    if committee == "unknown":
        route = "미정"
    elif pseudo_no_consent:
        route = "A"
    elif committee == "public":
        route = "B"
    else:
        route = "C"
    return route, committee, trace


