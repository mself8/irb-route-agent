def validate(data):
    errs = []
    cases = data["cases"]
    if data.get("seed") != SEED:
        errs.append("seed 불일치")
    if len(cases) != N_TOTAL:
        errs.append(f"사례 수 {len(cases)} ≠ {N_TOTAL}")
    ids = [c["id"] for c in cases]
    if len(set(ids)) != len(ids):
        errs.append("id 중복")
    for c in cases:
        cid, f, plan = c["id"], c["facts_gold"], c["plan"]
        e = lambda m: errs.append(f"{cid}: {m}")
        if list(f) != FKEYS:
            e("facts_gold 키가 F01~F18이 아님")
        for k, allowed in CHOICES.items():
            if f[k] is not None and f[k] not in allowed:
                e(f"{k} 값 {f[k]!r} 허용 밖")
        if f["F01"] is None:
            e("F01 없음")
        for k in ("F07", "F08", "F12", "F16"):
            if f[k] is not None and not isinstance(f[k], list):
                e(f"{k}는 목록이어야 함")
        if f["F07"] and any(x not in SENSITIVE for x in f["F07"]):
            e(f"F07 값 {f['F07']} 허용 밖")
        if f["F08"] and any(x not in VULNERABLE for x in f["F08"]):
            e(f"F08 값 {f['F08']} 허용 밖")
        if f["F16"] and any(x not in ID_NAMES for x in f["F16"]):
            e(f"F16 값 {f['F16']} 허용 밖")
        if f["F13"] is not None and not re.fullmatch(r"\d{4}-\d{2}-\d{2} ~ \d{4}-\d{2}-\d{2}", f["F13"]):
            e("F13 형식")
        if f["F15"] is not None and not isinstance(f["F15"], int):
            e("F15는 정수")
        if c["route_expected"] not in ROUTES or c["committee_expected"] not in COMMITTEES:
            e("경로·위원회 라벨")
        if not all(re.fullmatch(r"[GTSJECPD]\d+", r) for r in c["decision_trace"]):
            e("규칙 ID 형식")
        if not "2026-11-01" <= c["target_start_date"] <= "2027-06-30":
            e("목표 개시일 범위")
        if c["institution"] not in ALL_INST:
            e("기관 이름")
        if c["strata"].get("origin") not in ("CRIS 원본 변형", "시나리오 생성"):
            e("origin 표시")
        n_lines = plan.count("\n") + 1
        if c["strata"]["origin"] == "시나리오 생성" and not 6 <= n_lines <= 12:
            e(f"줄 수 {n_lines}")
        for p in c["pii_gold"]:
            if p["text"] not in plan:
                e(f"개인정보 {p['type']}가 계획서에 없음")
        # 값이 있는 사실은 계획서에 드러나야 한다
        for k, table in KW.items():
            v = f[k]
            if v is not None and not re.search(table[v], plan):
                e(f"{k}={v} 표현이 계획서에 없음")
        if f["F07"]:
            for x in f["F07"]:
                if x not in plan:
                    e(f"F07 {x} 없음")
        elif f["F07"] == [] and "민감정보" not in plan:
            e("F07=[] 문장 없음")
        if f["F08"]:
            for x in f["F08"]:
                if not re.search(F08_KW[x], plan):
                    e(f"F08 {x} 없음")
        elif f["F08"] == [] and not re.search(ADULT_RE, plan):
            e("F08=[] 문장 없음")
        for x in f["F12"] or []:
            if x not in plan:
                e(f"F12 {x} 없음")
        if f["F16"]:
            for x in f["F16"]:
                if x not in plan:
                    e(f"F16 {x} 없음")
        elif f["F16"] == [] and not re.search(r"기록하지 않|수집하지 않|남기지 않", plan):
            e("F16=[] 문장 없음")
        if f["F13"]:
            s, t = f["F13"].split(" ~ ")
            ok = False
            for fmt in (lambda d: d, lambda d: "{}년 {}월 {}일".format(*map(int, d.split("-"))),
                        lambda d: d.replace("-", ".") + "."):
                if fmt(s) in plan and fmt(t) in plan:
                    ok = True
            if not ok:
                e("F13 날짜가 계획서에 없음")
        if f["F15"] is not None and str(f["F15"]) not in plan:
            e("F15 인원이 계획서에 없음")
        # 값이 없는 사실은 계획서에 없어야 한다 (가벼운 확인)
        for k, pat in ABSENT.items():
            if f[k] is None and re.search(pat, plan):
                e(f"{k}=None인데 계획서에 '{re.search(pat, plan).group(0)}' 있음")
        # 정답이 판정 함수와 맞는지 다시 계산
        if gold_route(c) != (c["route_expected"], c["committee_expected"], c["decision_trace"]):
            e("정답 재계산 불일치")
    return errs


def report(data):
    cases = data["cases"]
    print(f"사례 {len(cases)}건")
    for key in ["origin", "연구 유형", "세부", "데이터 상태", "동의", "소속·보유 기관", "제출처 기관", "IRB 협약",
                "임상시험", "결합·반출"]:
        cnt = Counter(c["strata"][key] for c in cases)
        print(f"- {key}: " + ", ".join(f"{k} {v}" for k, v in cnt.most_common()))
    spr = Counter(x for c in cases for x in c["strata"]["뿌림"])
    print("- 뿌림: " + ", ".join(f"{k} {v}" for k, v in spr.most_common()))
    months = Counter(c["target_start_date"][:7] for c in cases)
    print("- 목표 개시월: " + ", ".join(f"{k} {months[k]}" for k in sorted(months)))
    for origin in ("시나리오 생성", "CRIS 원본 변형", None):
        sub = [c for c in cases if origin is None or c["strata"]["origin"] == origin]
        r = Counter(c["route_expected"] for c in sub)
        m = Counter(c["committee_expected"] for c in sub)
        print(f"- 정답 경로({origin or '전체'}): " + ", ".join(f"{k} {v}" for k, v in r.most_common())
              + " / 위원회: " + ", ".join(f"{k} {v}" for k, v in m.most_common()))
    lines = Counter(c["plan"].count("\n") + 1 for c in cases)
    print("- 계획서 줄 수: " + ", ".join(f"{k}줄 {lines[k]}" for k in sorted(lines)))


