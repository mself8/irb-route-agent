def j(word, p):
    """조사를 붙인다. p는 받침 있을 때 형태(을·이·은·과)."""
    other = {"을": "를", "이": "가", "은": "는", "과": "와"}[p]
    ch = word[-1]
    if "가" <= ch <= "힣":
        return word + (p if (ord(ch) - 0xAC00) % 28 else other)
    return word + (p if ch in "013678LMN" else other)


def pick(rng, options, **kw):
    """문장 후보 중 하나를 골라 채운다."""
    return rng.choice(options).format(**kw)


def dot(items):
    return "·".join(items)


def date_text(rng, s, e):
    """연구 기간 표기. 세 가지 중 하나."""
    return rng.choice([
        f"{s.isoformat()} ~ {e.isoformat()}",
        f"{s.year}년 {s.month}월 {s.day}일부터 {e.year}년 {e.month}월 {e.day}일까지",
        f"{s:%Y.%m.%d.} ~ {e:%Y.%m.%d.}",
    ])


def add_months(d, m):
    y, mo = divmod(d.month - 1 + m, 12)
    return date(d.year + y, mo + 1, 1)


