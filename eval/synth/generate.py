def make_slots(rng):
    slots = []
    for f01, (subs, cons, states) in SCEN_PLAN.items():
        s, c, d = quota(rng, subs), quota(rng, cons), quota(rng, states)
        for i in range(len(s)):
            slots.append({"f01": f01, "sub": s[i], "consent": c[i], "state": d[i]})
    rng.shuffle(slots)
    return slots


